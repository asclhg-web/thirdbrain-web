function sect(title, paras, len) {
  return [
    new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun({ text: title, bold: true })], spacing: { before: 400 } }),
    ...paras.map(t => new Paragraph({ children: [new TextRun(t)], spacing: { after: 240, line: 340 } })),
    new Paragraph({ children: [new TextRun({ text: `(공백 포함 ${len}자)`, size: 18, color: "888888" })] }),
  ];
}
